// GeneratedFile is the name of the file, which [Generate] writes into a package.
const GeneratedFile = "gostrict_gen.go"

// Generate returns the Go source of the functions of the main package as [Funcs], which cross the boundary of an
// engine without reflection. A header package gets a function Host, which implements its functions natively for
// an engine like goja. Any other package gets a function Exports with its exported functions for the native
// engine and a type Client, which calls them in any engine with the types of Go. The file is excluded from the
// subset by a build constraint, because it uses any.
func Generate(prog *Program) ([]byte, error) {
	g := &generator{pkg: prog.Main, imports: map[string]string{}, helpers: map[string]int{}}
	if prog.Main.Kind == KindHeader {
		return g.header()
	}
	return g.exports()
}

type generator struct {
	pkg     *Package
	imports map[string]string
	// helpers maps the types of records and lists to the number of their conversion functions
	helpers map[string]int
	code    bytes.Buffer
	pending []types.Type
}

func (g *generator) qual(p *types.Package) string {
	if p == g.pkg.Types {
		return ""
	}
	g.imports[p.Path()] = p.Name()
	return p.Name()
}

// name returns the name of a declaration of the generated file, which does not collide with one of the package.
func (g *generator) name(base string) string {
	if g.pkg.Types.Scope().Lookup(base) == nil {
		return base
	}
	return "Gostrict" + base
}

func (g *generator) typeString(t types.Type) string {
	return types.TypeString(t, g.qual)
}

func (g *generator) file(body string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("//go:build !gostrict\n\n// Code generated by gostrict gen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\nimport (\n", g.pkg.Name)
	paths := []string{"go.wdy.de/nago/pkg/gostrict"}
	for p := range g.imports {
		paths = append(paths, p)
	}
	slices.Sort(paths)
	paths = slices.Compact(paths)
	for _, p := range paths {
		fmt.Fprintf(&buf, "\t%q\n", p)
	}
	buf.WriteString(")\n\n")
	buf.WriteString(body)
	return format.Source(buf.Bytes())
}

func (g *generator) header() ([]byte, error) {
	p := g.pkg
	var body bytes.Buffer
	fmt.Fprintf(&body, "// %s implements the functions of this header package natively, e.g. for an engine like goja.\nfunc %s() gostrict.Funcs {\n\treturn gostrict.Funcs{\n", g.name("Host"), g.name("Host"))

	for _, name := range p.Types.Scope().Names() {
		fn, ok := p.Types.Scope().Lookup(name).(*types.Func)
		if !ok || !fn.Exported() {
			continue
		}
		instances, ok := instantiations(fn)
		if !ok {
			continue
		}
		for _, targs := range instances {
			sig := fn.Signature()
			call := name
			if len(targs) > 0 {
				inst, err := types.Instantiate(nil, fn.Type(), targs, true)
				if err != nil {
					return nil, err
				}
				sig = inst.(*types.Signature)
				var args []string
				for _, t := range targs {
					args = append(args, g.typeString(t))
				}
				call += "[" + strings.Join(args, ", ") + "]"
			}
			if _, ok := signature(name, sig); !ok {
				continue
			}

			var args, results, values []string
			for i := 0; i < sig.Params().Len(); i++ {
				t := sig.Params().At(i).Type()
				arg := fmt.Sprintf("args[%d]", i)
				if f := handleField(t); f != nil {
					if f.Pkg() != p.Types {
						return nil, fmt.Errorf("%s takes the handle %s of another package", name, t)
					}
					g.imports[jsPath] = "js"
					args = append(args, fmt.Sprintf("%s{%s: %s.(js.Ref)}", g.typeString(t), f.Name(), arg))
					continue
				}
				args = append(args, g.fromNeutral(arg, t))
			}
			for i := 0; i < sig.Results().Len(); i++ {
				r := fmt.Sprintf("r%d", i)
				results = append(results, r)
				if f := handleField(sig.Results().At(i).Type()); f != nil {
					if f.Pkg() != p.Types {
						return nil, fmt.Errorf("%s returns the handle of another package", name)
					}
					r += "." + f.Name()
				} else {
					r = g.toNeutral(r, sig.Results().At(i).Type())
				}
				values = append(values, r)
			}
			writeAdapter(&body, externKey(fn, targs), call, args, results, values)
		}
	}
	body.WriteString("\t}\n}\n")
	g.writeHelpers()
	body.Write(g.code.Bytes())
	return g.file(body.String())
}

func writeAdapter(buf *bytes.Buffer, key, call string, args, results, values []string) {
	fmt.Fprintf(buf, "\t\t%q: func(args []any) []any {\n", key)
	c := fmt.Sprintf("%s(%s)", call, strings.Join(args, ", "))
	if len(results) == 0 {
		fmt.Fprintf(buf, "\t\t\t%s\n\t\t\treturn nil\n", c)
	} else {
		fmt.Fprintf(buf, "\t\t\t%s := %s\n\t\t\treturn []any{%s}\n", strings.Join(results, ", "), c, strings.Join(values, ", "))
	}
	buf.WriteString("\t\t},\n")
}

type export struct {
	fn  *types.Func
	sig Func
}

func (g *generator) exports() ([]byte, error) {
	p := g.pkg
	bnd := newBoundary()
	var exports []export
	for _, name := range p.Types.Scope().Names() {
		fn, ok := p.Types.Scope().Lookup(name).(*types.Func)
		if !ok || !fn.Exported() {
			continue
		}
		if sig, ok := bnd.exportSignature(name, fn.Signature()); ok {
			exports = append(exports, export{fn: fn, sig: sig})
		}
	}

	var body bytes.Buffer
	fmt.Fprintf(&body, "// %s returns the exported functions of this package, e.g. for the native engine.\nfunc %s() gostrict.Funcs {\n\treturn gostrict.Funcs{\n", g.name("Exports"), g.name("Exports"))
	for _, e := range exports {
		sig := e.fn.Signature()
		var args, results, values []string
		for i := 0; i < sig.Params().Len(); i++ {
			args = append(args, g.fromNeutral(fmt.Sprintf("args[%d]", i), sig.Params().At(i).Type()))
		}
		for i := 0; i < sig.Results().Len(); i++ {
			r := fmt.Sprintf("r%d", i)
			results = append(results, r)
			values = append(values, g.toNeutral(r, sig.Results().At(i).Type()))
		}
		writeAdapter(&body, e.fn.Name(), e.fn.Name(), args, results, values)
	}
	body.WriteString("\t}\n}\n")

	g.client(&body, exports)
	g.messages(&body, exports)
	g.writeHelpers()
	body.Write(g.code.Bytes())
	return g.file(body.String())
}

// client writes a type, which calls the exported functions in an instance of any engine with the types of Go, so
// that the caller needs no conversion.
func (g *generator) client(buf *bytes.Buffer, exports []export) {
	g.imports["context"] = "context"
	client := g.name("Client")
	fmt.Fprintf(buf, "\n// %s calls the exported functions of this package in an instance of its bundle, e.g. in goja.\n", client)
	fmt.Fprintf(buf, "type %s struct {\n\tInstance gostrict.Instance\n}\n", client)
	for _, e := range exports {
		sig := e.fn.Signature()
		var params, args, results, zeros, conv []string
		for i := 0; i < sig.Params().Len(); i++ {
			v := sig.Params().At(i)
			name := v.Name()
			if name == "" || name == "_" || name == "ctx" || name == "c" || name == "res" || name == "err" {
				name = fmt.Sprintf("p%d", i)
			}
			params = append(params, name+" "+g.clientType(v.Type()))
			args = append(args, g.clientToNeutral(name, v.Type()))
		}
		for i := 0; i < sig.Results().Len(); i++ {
			t := sig.Results().At(i).Type()
			results = append(results, g.clientType(t))
			zeros = append(zeros, g.zero(t))
			conv = append(conv, g.clientFromNeutral(fmt.Sprintf("res[%d]", i), t))
		}
		results = append(results, "error")
		zeros = append(zeros, "err")
		conv = append(conv, "nil")

		callArgs := ""
		if len(args) > 0 {
			callArgs = ", " + strings.Join(args, ", ")
		}
		fmt.Fprintf(buf, "\nfunc (c %s) %s(%s) (%s) {\n", client, e.fn.Name(), strings.Join(append([]string{"ctx context.Context"}, params...), ", "), strings.Join(results, ", "))
		fmt.Fprintf(buf, "\tres, err := c.Instance.Call(ctx, %q%s)\n", e.fn.Name(), callArgs)
		fmt.Fprintf(buf, "\tif err != nil {\n\t\treturn %s\n\t}\n", strings.Join(zeros, ", "))
		if sig.Results().Len() == 0 {
			buf.WriteString("\t_ = res\n")
		}
		fmt.Fprintf(buf, "\treturn %s\n}\n", strings.Join(conv, ", "))
	}
	buf.WriteString("\nfunc gostrictErrorOf(v any) error {\n\terr, _ := v.(error)\n\treturn err\n}\n")
}

func n0(g *generator, t types.Type) int {
	return g.helpers[typeKey(t)]
}

// messages writes the side of the backend: a function, which encodes each message, which the program handles,
// an interface with a method for each message, which the program sends, and a function, which dispatches them.
func (g *generator) messages(buf *bytes.Buffer, exports []export) {
	var in, out []types.Type
	seen := map[string]bool{}
	for _, e := range exports {
		sig := e.fn.Signature()
		if isHandler(e.sig) {
			if t := sig.Params().At(1).Type(); !seen["in"+typeKey(t)] {
				seen["in"+typeKey(t)] = true
				in = append(in, t)
			}
		}
		for i, r := range e.sig.Results {
			if r.Kind != ValueOut {
				continue
			}
			t := types.Unalias(sig.Results().At(i).Type()).(*types.Named).TypeArgs().At(0)
			if !seen["out"+typeKey(t)] {
				seen["out"+typeKey(t)] = true
				out = append(out, t)
			}
		}
	}
	if len(in) == 0 && len(out) == 0 {
		return
	}

	for _, t := range in {
		name := types.Unalias(t).(*types.Named).Obj().Name()
		fn := g.name(name + "Message")
		if isSealed(t) {
			// the message is the record of the variant
			fmt.Fprintf(buf, "\n// %s encodes a message for the program, see gostrict.Session.Deliver.\nfunc %s(m %s) gostrict.Message {\n\tv := %s\n\treturn gostrict.Message{Type: v.Tag, Fields: v.Fields}\n}\n", fn, fn, g.typeString(t), g.toNeutral("m", t))
			continue
		}
		fmt.Fprintf(buf, "\n// %s encodes a message for the program, see gostrict.Session.Deliver.\nfunc %s(m %s) gostrict.Message {\n\treturn gostrict.Message{Type: %q, Fields: %s}\n}\n", fn, fn, g.typeString(t), typeKey(t), g.toNeutral("m", t))
	}

	if len(out) == 0 {
		return
	}
	backend := g.name("Backend")
	fmt.Fprintf(buf, "\n// %s receives the messages, which the program sends.\ntype %s interface {\n", backend, backend)
	for _, t := range out {
		name := types.Unalias(t).(*types.Named).Obj().Name()
		fmt.Fprintf(buf, "\t%s(ctx context.Context, m %s) error\n", name, g.typeString(t))
	}
	buf.WriteString("}\n")
	dispatch := g.name("Dispatch")
	fmt.Fprintf(buf, "\n// %s decodes a message of the program and passes it to the backend.\nfunc %s(ctx context.Context, b %s, m gostrict.Message) error {\n\tswitch m.Type {\n", dispatch, dispatch, backend)
	for _, t := range out {
		name := types.Unalias(t).(*types.Named).Obj().Name()
		if variants, ok := sealedVariants(t); ok {
			for _, v := range variants {
				fmt.Fprintf(buf, "\tcase %q:\n\t\treturn b.%s(ctx, %s)\n", typeKey(v), name, g.fromNeutral("any(gostrict.Variant{Tag: m.Type, Fields: m.Fields})", t))
			}
			continue
		}
		fmt.Fprintf(buf, "\tcase %q:\n\t\treturn b.%s(ctx, %s)\n", typeKey(t), name, g.fromNeutral("any(m.Fields)", t))
	}
	buf.WriteString("\t}\n\treturn fmt.Errorf(\"unknown message %s\", m.Type)\n}\n")
	g.imports["fmt"] = "fmt"
}

func stateElem(t types.Type) (types.Type, bool) {
	if p, ok := t.Underlying().(*types.Pointer); ok && isStruct(p.Elem()) {
		return p.Elem(), true
	}
	return nil, false
}

// clientType is the type of a parameter or result of the client: a state is a typed token.
func (g *generator) clientType(t types.Type) string {
	if elem, ok := stateElem(t); ok {
		return "gostrict.State[" + g.typeString(elem) + "]"
	}
	return g.typeString(t)
}

func (g *generator) clientToNeutral(expr string, t types.Type) string {
	if _, ok := stateElem(t); ok {
		return expr + ".Token"
	}
	return g.toNeutral(expr, t)
}

func (g *generator) clientFromNeutral(expr string, t types.Type) string {
	if elem, ok := stateElem(t); ok {
		return "gostrict.State[" + g.typeString(elem) + "]{Token: " + expr + ".(gostrict.Token)}"
	}
	return g.fromNeutral(expr, t)
}

func (g *generator) zero(t types.Type) string {
	if _, ok := stateElem(t); ok {
		return g.clientType(t) + "{}"
	}
	switch {
	case isError(t), isInterface(t):
		return "nil"
	case isStruct(t), isOpaque(t):
		return g.typeString(t) + "{}"
	}
	switch basicKind(t) {
	case types.Bool:
		return "false"
	case types.String:
		return `""`
	}
	return "0"
}

// fromNeutral converts the neutral value expr, see [ValueKind], into a value of t.
func (g *generator) fromNeutral(expr string, t types.Type) string {
	if isSealed(t) {
		return fmt.Sprintf("gostrictFrom%d(%s.(gostrict.Variant))", g.helper(t), expr)
	}
	if _, ok := stateElem(t); ok {
		return fmt.Sprintf("%s.(gostrict.Token).Value().(%s)", expr, g.typeString(t))
	}
	switch {
	case isError(t):
		return "gostrictErrorOf(" + expr + ")"
	case isOpaque(t), isStruct(t):
		return fmt.Sprintf("gostrictFrom%d(%s.([]any))", g.helper(t), expr)
	}
	basic := g.typeString(t.Underlying())
	if _, named := types.Unalias(t).(*types.Named); named {
		return fmt.Sprintf("%s(%s.(%s))", g.typeString(t), expr, basic)
	}
	return fmt.Sprintf("%s.(%s)", expr, basic)
}

// toNeutral converts expr of type t into its neutral value.
func (g *generator) toNeutral(expr string, t types.Type) string {
	if isSealed(t) {
		return fmt.Sprintf("gostrictTo%d(%s)", g.helper(t), expr)
	}
	if elem, ok := stateElem(t); ok {
		return fmt.Sprintf("gostrict.NewToken(%q, %s)", typeKey(elem), expr)
	}
	switch {
	case isError(t):
		return expr
	case isOpaque(t), isStruct(t):
		return fmt.Sprintf("gostrictTo%d(%s)", g.helper(t), expr)
	}
	if _, named := types.Unalias(t).(*types.Named); named {
		return fmt.Sprintf("%s(%s)", g.typeString(t.Underlying()), expr)
	}
	return expr
}

// helper returns the number of the conversion functions of a record or list type.
func (g *generator) helper(t types.Type) int {
	key := typeKey(t)
	if n, ok := g.helpers[key]; ok {
		return n
	}
	n := len(g.helpers) + 1
	g.helpers[key] = n
	g.pending = append(g.pending, t)
	return n
}

func (g *generator) writeHelpers() {
	for len(g.pending) > 0 {
		t := g.pending[0]
		g.pending = g.pending[1:]
		n := g.helpers[typeKey(t)]
		ts := g.typeString(t)

		if n := types.Unalias(t).(*types.Named); isOpaque(t) && n.Obj().Name() == "Out" {
			elem := n.TypeArgs().At(0)
			g.imports[msgPath] = "msg"
			fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(v []any) %s {\n\to := msg.New[%s]()\n\tfor _, e := range v {\n\t\to.Send(%s)\n\t}\n\treturn o\n}\n", n0(g, t), ts, g.typeString(elem), g.fromNeutral("e", elem))
			fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(o %s) []any {\n\tres := make([]any, 0, o.Len())\n\tfor e := range o.Values() {\n\t\tres = append(res, %s)\n\t}\n\treturn res\n}\n", n0(g, t), ts, g.toNeutral("e", elem))
			continue
		}

		if variants, ok := sealedVariants(t); ok {
			var from, to strings.Builder
			for _, v := range variants {
				fmt.Fprintf(&from, "\tcase %q:\n\t\treturn %s\n", typeKey(v), g.fromNeutral("any(x.Fields)", v))
				fmt.Fprintf(&to, "\tcase %s:\n\t\treturn gostrict.Variant{Tag: %q, Fields: %s}\n", g.typeString(v), typeKey(v), g.toNeutral("x", v))
			}
			fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(x gostrict.Variant) %s {\n\tswitch x.Tag {\n%s\t}\n\tpanic(\"unknown variant \" + x.Tag)\n}\n", n0(g, t), ts, from.String())
			fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(v %s) gostrict.Variant {\n\tswitch x := v.(type) {\n%s\t}\n\tpanic(\"unknown variant\")\n}\n", n0(g, t), ts, to.String())
			continue
		}

		if n := types.Unalias(t).(*types.Named); isOpaque(t) && n.Obj().Name() == "Map" {
			key, elem := n.TypeArgs().At(0), n.TypeArgs().At(1)
			g.imports[dictPath] = "dict"
			fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(v []any) %s {\n\tm := dict.New[%s, %s]()\n\tfor _, e := range v {\n\t\tkv := e.([]any)\n\t\tm.Set(%s, %s)\n\t}\n\treturn m\n}\n", n0(g, t), ts, g.typeString(key), g.typeString(elem), g.fromNeutral("kv[0]", key), g.fromNeutral("kv[1]", elem))
			fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(m %s) []any {\n\tres := make([]any, 0, m.Len())\n\tfor k, v := range m.All() {\n\t\tres = append(res, []any{%s, %s})\n\t}\n\treturn res\n}\n", n0(g, t), ts, g.toNeutral("k", key), g.toNeutral("v", elem))
			continue
		}

		if isOpaque(t) {
			elem := types.Unalias(t).(*types.Named).TypeArgs().At(0)
			g.imports[listPath] = "list"
			fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(v []any) %s {\n\tl := list.New[%s]()\n\tfor _, e := range v {\n\t\tl.Append(%s)\n\t}\n\treturn l\n}\n", n, ts, g.typeString(elem), g.fromNeutral("e", elem))
			fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(l %s) []any {\n\tres := make([]any, 0, l.Len())\n\tfor e := range l.Values() {\n\t\tres = append(res, %s)\n\t}\n\treturn res\n}\n", n, ts, g.toNeutral("e", elem))
			continue
		}

		st := t.Underlying().(*types.Struct)
		var fields, values []string
		for i := 0; i < st.NumFields(); i++ {
			f := st.Field(i)
			fields = append(fields, fmt.Sprintf("%s: %s", f.Name(), g.fromNeutral(fmt.Sprintf("v[%d]", i), f.Type())))
			values = append(values, g.toNeutral("x."+f.Name(), f.Type()))
		}
		fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(v []any) %s {\n\treturn %s{%s}\n}\n", n, ts, ts, strings.Join(fields, ", "))
		fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(x %s) []any {\n\treturn []any{%s}\n}\n", n, ts, strings.Join(values, ", "))
	}
}

// GenerateTS returns a TypeScript declaration of the functions of a header package, which a JavaScript host
// implements, e.g. a frontend, which binds three.js. The keys are the full names, which the bundle expects in
// the object of the host.
func GenerateTS(prog *Program) ([]byte, error) {
	p := prog.Main
	if p.Kind != KindHeader {
		return nil, fmt.Errorf("%s is not a header package", p.Path)
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gostrict gen. DO NOT EDIT.\n\n")
	buf.WriteString("// An error crosses the boundary as null or as the value of $errors_New(message) of the runtime.\n")
	buf.WriteString("export type GoError = { v: unknown; m: { Error(v: unknown): string } } | null;\n\n")
	fmt.Fprintf(&buf, "export interface Host {\n")
	for _, name := range p.Types.Scope().Names() {
		fn, ok := p.Types.Scope().Lookup(name).(*types.Func)
		if !ok || !fn.Exported() {
			continue
		}
		instances, ok := instantiations(fn)
		if !ok {
			continue
		}
		for _, targs := range instances {
			sig := fn.Signature()
			if len(targs) > 0 {
				inst, err := types.Instantiate(nil, fn.Type(), targs, true)
				if err != nil {
					return nil, err
				}
				sig = inst.(*types.Signature)
			}
			f, ok := signature(externKey(fn, targs), sig)
			if !ok {
				continue
			}

			var params []string
			for i, t := range f.Params {
				params = append(params, fmt.Sprintf("%s: %s", sig.Params().At(i).Name(), tsType(t.Kind)))
			}
			var results []string
			for _, t := range f.Results {
				results = append(results, tsType(t.Kind))
			}
			result := "void"
			switch len(results) {
			case 1:
				result = results[0]
			case 0:
			default:
				result = "[" + strings.Join(results, ", ") + "]"
			}
			fmt.Fprintf(&buf, "\t%q(%s): %s;\n", f.Name, strings.Join(params, ", "), result)
		}
	}
	buf.WriteString("}\n")
	return buf.Bytes(), nil
}

func tsType(k ValueKind) string {
	switch k {
	case ValueHandle:
		return "object"
	case ValueBool:
		return "boolean"
	case ValueString:
		return "string"
	case ValueError:
		return "GoError"
	}
	return "number"
}
