// GeneratedFile is the name of the file, which [Generate] writes into a package.
const GeneratedFile = "gostrict_gen.go"

// Generate returns the Go source of the functions of a header package as [Funcs], whose function Host implements
// them natively for an engine like goja. It is needed, because reflection can neither instantiate the generic
// functions of a header package nor construct its handles. A program needs no generated code. The file is excluded
// from the subset by a build constraint.
func Generate(prog *Program) ([]byte, error) {
	g := &generator{pkg: prog.Main, imports: map[string]string{}, helpers: map[string]int{}}
	if prog.Main.Kind != KindHeader {
		return nil, fmt.Errorf("%s is no header package: a program needs no generated code, see native.Reflect, gostrict.Call and gostrict.Router", prog.Main.Path)
	}
	return g.header()
}

type generator struct {
	pkg     *Package
	imports map[string]string
	// helpers maps the types of records and lists to the number of their conversion functions
	helpers map[string]int
	code    bytes.Buffer
	pending []types.Type
}

func (g *generator) qual(p *types.Package) string {
	if p == g.pkg.Types {
		return ""
	}
	g.imports[p.Path()] = p.Name()
	return p.Name()
}

// name returns the name of a declaration of the generated file, which does not collide with one of the package.
func (g *generator) name(base string) string {
	if g.pkg.Types.Scope().Lookup(base) == nil {
		return base
	}
	return "Gostrict" + base
}

func (g *generator) typeString(t types.Type) string {
	return types.TypeString(t, g.qual)
}

func (g *generator) file(body string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("//go:build !gostrict\n\n// Code generated by gostrict gen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\nimport (\n", g.pkg.Name)
	paths := []string{"go.wdy.de/nago/pkg/gostrict"}
	for p := range g.imports {
		paths = append(paths, p)
	}
	slices.Sort(paths)
	paths = slices.Compact(paths)
	for _, p := range paths {
		fmt.Fprintf(&buf, "\t%q\n", p)
	}
	buf.WriteString(")\n\n")
	buf.WriteString(body)
	return format.Source(buf.Bytes())
}

func (g *generator) header() ([]byte, error) {
	p := g.pkg
	var body bytes.Buffer
	fmt.Fprintf(&body, "// %s implements the functions of this header package natively, e.g. for an engine like goja.\nfunc %s() gostrict.Funcs {\n\treturn gostrict.Funcs{\n", g.name("Host"), g.name("Host"))

	for _, name := range p.Types.Scope().Names() {
		fn, ok := p.Types.Scope().Lookup(name).(*types.Func)
		if !ok || !fn.Exported() {
			continue
		}
		instances, ok := instantiations(fn)
		if !ok {
			continue
		}
		for _, targs := range instances {
			sig := fn.Signature()
			call := name
			if len(targs) > 0 {
				inst, err := types.Instantiate(nil, fn.Type(), targs, true)
				if err != nil {
					return nil, err
				}
				sig = inst.(*types.Signature)
				var args []string
				for _, t := range targs {
					args = append(args, g.typeString(t))
				}
				call += "[" + strings.Join(args, ", ") + "]"
			}
			if _, ok := signature(name, sig); !ok {
				continue
			}

			var args, results, values []string
			for i := 0; i < sig.Params().Len(); i++ {
				arg, err := g.fromBoundary(fmt.Sprintf("args[%d]", i), sig.Params().At(i).Type())
				if err != nil {
					return nil, fmt.Errorf("%s: %w", name, err)
				}
				args = append(args, arg)
			}
			for i := 0; i < sig.Results().Len(); i++ {
				r := fmt.Sprintf("r%d", i)
				results = append(results, r)
				v, err := g.toBoundary(r, sig.Results().At(i).Type())
				if err != nil {
					return nil, fmt.Errorf("%s: %w", name, err)
				}
				values = append(values, v)
			}
			writeAdapter(&body, externKey(fn, targs), call, args, results, values)
		}
	}
	body.WriteString("\t}\n}\n")
	if err := g.writeHelpers(); err != nil {
		return nil, err
	}
	body.Write(g.code.Bytes())
	return g.file(body.String())
}

// fromBoundary converts the neutral value expr of a parameter of a header function into t, also a handle of the
// package, which only it can construct.
func (g *generator) fromBoundary(expr string, t types.Type) (string, error) {
	if f := handleField(t); f != nil && !isBig(t) {
		if f.Pkg() != g.pkg.Types {
			return "", fmt.Errorf("the handle %s belongs to another package", t)
		}
		g.imports[jsPath] = "js"
		return fmt.Sprintf("%s{%s: %s.(js.Ref)}", g.typeString(t), f.Name(), expr), nil
	}
	return g.fromNeutral(expr, t), nil
}

// toBoundary converts expr of type t, also a handle of the package, into its neutral value.
func (g *generator) toBoundary(expr string, t types.Type) (string, error) {
	if f := handleField(t); f != nil && !isBig(t) {
		if f.Pkg() != g.pkg.Types {
			return "", fmt.Errorf("the handle %s belongs to another package", t)
		}
		return expr + "." + f.Name(), nil
	}
	return g.toNeutral(expr, t), nil
}

func writeAdapter(buf *bytes.Buffer, key, call string, args, results, values []string) {
	fmt.Fprintf(buf, "\t\t%q: func(args []any) []any {\n", key)
	c := fmt.Sprintf("%s(%s)", call, strings.Join(args, ", "))
	if len(results) == 0 {
		fmt.Fprintf(buf, "\t\t\t%s\n\t\t\treturn nil\n", c)
	} else {
		fmt.Fprintf(buf, "\t\t\t%s := %s\n\t\t\treturn []any{%s}\n", strings.Join(results, ", "), c, strings.Join(values, ", "))
	}
	buf.WriteString("\t\t},\n")
}

func n0(g *generator, t types.Type) int {
	return g.helpers[typeKey(t)]
}

func stateElem(t types.Type) (types.Type, bool) {
	if p, ok := t.Underlying().(*types.Pointer); ok && isStruct(p.Elem()) {
		return p.Elem(), true
	}
	return nil, false
}

// fromNeutral converts the neutral value expr, see [ValueKind], into a value of t.
func (g *generator) fromNeutral(expr string, t types.Type) string {
	if _, ok := t.Underlying().(*types.Signature); ok {
		return fmt.Sprintf("gostrictFunc%d(%s.(gostrict.Callback))", g.helper(t), expr)
	}
	if isBig(t) {
		ts := g.typeString(t)
		return fmt.Sprintf("%s{}.HostFromString(%s.(string)).(%s)", ts, expr, ts)
	}
	if isSealed(t) {
		return fmt.Sprintf("gostrictFrom%d(%s.(gostrict.Variant))", g.helper(t), expr)
	}
	if _, ok := stateElem(t); ok {
		return fmt.Sprintf("%s.(gostrict.Token).Value().(%s)", expr, g.typeString(t))
	}
	switch {
	case isError(t):
		return "gostrict.ErrorOf(" + expr + ")"
	case isOpaque(t), isStruct(t):
		return fmt.Sprintf("gostrictFrom%d(%s.([]any))", g.helper(t), expr)
	}
	basic := g.typeString(t.Underlying())
	if _, named := types.Unalias(t).(*types.Named); named {
		return fmt.Sprintf("%s(%s.(%s))", g.typeString(t), expr, basic)
	}
	return fmt.Sprintf("%s.(%s)", expr, basic)
}

// toNeutral converts expr of type t into its neutral value.
func (g *generator) toNeutral(expr string, t types.Type) string {
	if isBig(t) {
		return expr + ".HostString()"
	}
	if isSealed(t) {
		return fmt.Sprintf("gostrictTo%d(%s)", g.helper(t), expr)
	}
	if elem, ok := stateElem(t); ok {
		return fmt.Sprintf("gostrict.NewToken(%q, %s)", typeKey(elem), expr)
	}
	switch {
	case isError(t):
		return expr
	case isOpaque(t), isStruct(t):
		return fmt.Sprintf("gostrictTo%d(%s)", g.helper(t), expr)
	}
	if _, named := types.Unalias(t).(*types.Named); named {
		return fmt.Sprintf("%s(%s)", g.typeString(t.Underlying()), expr)
	}
	return expr
}

// helper returns the number of the conversion functions of a record or list type.
func (g *generator) helper(t types.Type) int {
	key := typeKey(t)
	if n, ok := g.helpers[key]; ok {
		return n
	}
	n := len(g.helpers) + 1
	g.helpers[key] = n
	g.pending = append(g.pending, t)
	return n
}

func (g *generator) writeHelpers() error {
	for len(g.pending) > 0 {
		t := g.pending[0]
		g.pending = g.pending[1:]
		n := g.helpers[typeKey(t)]
		ts := g.typeString(t)

		if fs, ok := t.Underlying().(*types.Signature); ok {
			if err := g.writeCallback(n, ts, fs); err != nil {
				return err
			}
			continue
		}

		if n := types.Unalias(t).(*types.Named); isOpaque(t) && n.Obj().Name() == "Out" {
			elem := n.TypeArgs().At(0)
			g.imports[msgPath] = "msg"
			fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(v []any) %s {\n\to := msg.New[%s]()\n\tfor _, e := range v {\n\t\to.Send(%s)\n\t}\n\treturn o\n}\n", n0(g, t), ts, g.typeString(elem), g.fromNeutral("e", elem))
			fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(o %s) []any {\n\tres := make([]any, 0, o.Len())\n\tfor e := range o.Values() {\n\t\tres = append(res, %s)\n\t}\n\treturn res\n}\n", n0(g, t), ts, g.toNeutral("e", elem))
			continue
		}

		if variants, ok := sealedVariants(t); ok {
			var from, to strings.Builder
			for _, v := range variants {
				fmt.Fprintf(&from, "\tcase %q:\n\t\treturn %s\n", typeKey(v), g.fromNeutral("any(x.Fields)", v))
				fmt.Fprintf(&to, "\tcase %s:\n\t\treturn gostrict.Variant{Tag: %q, Fields: %s}\n", g.typeString(v), typeKey(v), g.toNeutral("x", v))
			}
			fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(x gostrict.Variant) %s {\n\tswitch x.Tag {\n%s\t}\n\tpanic(\"unknown variant \" + x.Tag)\n}\n", n0(g, t), ts, from.String())
			fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(v %s) gostrict.Variant {\n\tswitch x := v.(type) {\n%s\t}\n\tpanic(\"unknown variant\")\n}\n", n0(g, t), ts, to.String())
			continue
		}

		if n := types.Unalias(t).(*types.Named); isOpaque(t) && n.Obj().Name() == "Map" {
			key, elem := n.TypeArgs().At(0), n.TypeArgs().At(1)
			g.imports[dictPath] = "dict"
			fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(v []any) %s {\n\tm := dict.New[%s, %s]()\n\tfor _, e := range v {\n\t\tkv := e.([]any)\n\t\tm.Set(%s, %s)\n\t}\n\treturn m\n}\n", n0(g, t), ts, g.typeString(key), g.typeString(elem), g.fromNeutral("kv[0]", key), g.fromNeutral("kv[1]", elem))
			fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(m %s) []any {\n\tres := make([]any, 0, m.Len())\n\tfor k, v := range m.All() {\n\t\tres = append(res, []any{%s, %s})\n\t}\n\treturn res\n}\n", n0(g, t), ts, g.toNeutral("k", key), g.toNeutral("v", elem))
			continue
		}

		if isOpaque(t) {
			elem := types.Unalias(t).(*types.Named).TypeArgs().At(0)
			g.imports[listPath] = "list"
			fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(v []any) %s {\n\tl := list.New[%s]()\n\tfor _, e := range v {\n\t\tl.Append(%s)\n\t}\n\treturn l\n}\n", n, ts, g.typeString(elem), g.fromNeutral("e", elem))
			fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(l %s) []any {\n\tres := make([]any, 0, l.Len())\n\tfor e := range l.Values() {\n\t\tres = append(res, %s)\n\t}\n\treturn res\n}\n", n, ts, g.toNeutral("e", elem))
			continue
		}

		st := t.Underlying().(*types.Struct)
		var fields, values []string
		for i := 0; i < st.NumFields(); i++ {
			f := st.Field(i)
			fields = append(fields, fmt.Sprintf("%s: %s", f.Name(), g.fromNeutral(fmt.Sprintf("v[%d]", i), f.Type())))
			values = append(values, g.toNeutral("x."+f.Name(), f.Type()))
		}
		fmt.Fprintf(&g.code, "\nfunc gostrictFrom%d(v []any) %s {\n\treturn %s{%s}\n}\n", n, ts, ts, strings.Join(fields, ", "))
		fmt.Fprintf(&g.code, "\nfunc gostrictTo%d(x %s) []any {\n\treturn []any{%s}\n}\n", n, ts, strings.Join(values, ", "))
	}
	return nil
}

// writeCallback writes the function, which turns a callback into a Go function of the signature. If the engine
// fails, the function returns zero values or the error, if a result is an error, and the instance reports the
// error, see [Callback].
func (g *generator) writeCallback(n int, ts string, fs *types.Signature) error {
	var params, args, zeros, results, rtypes []string
	for i := 0; i < fs.Params().Len(); i++ {
		pt := fs.Params().At(i).Type()
		a := fmt.Sprintf("a%d", i)
		params = append(params, a+" "+g.typeString(pt))
		v, err := g.toBoundary(a, pt)
		if err != nil {
			return err
		}
		args = append(args, v)
	}
	for i := 0; i < fs.Results().Len(); i++ {
		rt := fs.Results().At(i).Type()
		zeros = append(zeros, fmt.Sprintf("z%d", i))
		rtypes = append(rtypes, g.typeString(rt))
		r, err := g.fromBoundary(fmt.Sprintf("res[%d]", i), rt)
		if err != nil {
			return err
		}
		results = append(results, r)
	}

	ret := strings.Join(rtypes, ", ")
	if len(rtypes) > 1 {
		ret = "(" + ret + ")"
	}
	fmt.Fprintf(&g.code, "\nfunc gostrictFunc%d(cb gostrict.Callback) %s {\n\treturn func(%s) %s {\n", n, ts, strings.Join(params, ", "), ret)
	call := fmt.Sprintf("cb.Call(%s)", strings.Join(args, ", "))
	if len(results) == 0 {
		fmt.Fprintf(&g.code, "\t\t_, _ = %s\n\t}\n}\n", call)
		return nil
	}
	fmt.Fprintf(&g.code, "\t\tres, err := %s\n\t\tif err != nil {\n", call)
	for i, z := range zeros {
		if isError(fs.Results().At(i).Type()) {
			// the program could not return its error, so the error of the engine replaces it
			zeros[i] = "err"
			continue
		}
		fmt.Fprintf(&g.code, "\t\t\tvar %s %s\n", z, g.typeString(fs.Results().At(i).Type()))
	}
	fmt.Fprintf(&g.code, "\t\t\treturn %s\n\t\t}\n\t\treturn %s\n\t}\n}\n", strings.Join(zeros, ", "), strings.Join(results, ", "))
	return nil
}

// GenerateTS returns a TypeScript declaration of the functions of a header package, which a JavaScript host
// implements, e.g. a frontend, which binds three.js. The keys are the full names, which the bundle expects in
// the object of the host.
func GenerateTS(prog *Program) ([]byte, error) {
	p := prog.Main
	if p.Kind != KindHeader {
		return nil, fmt.Errorf("%s is not a header package", p.Path)
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gostrict gen. DO NOT EDIT.\n\n")
	buf.WriteString("// An error crosses the boundary as null or as the value of $errors_New(message) of the runtime.\n")
	buf.WriteString("export type GoError = { v: unknown; m: { Error(v: unknown): string } } | null;\n\n")
	var host bytes.Buffer
	bnd := newBoundary()
	fmt.Fprintf(&host, "export interface Host {\n")
	for _, name := range p.Types.Scope().Names() {
		fn, ok := p.Types.Scope().Lookup(name).(*types.Func)
		if !ok || !fn.Exported() {
			continue
		}
		instances, ok := instantiations(fn)
		if !ok {
			continue
		}
		for _, targs := range instances {
			sig := fn.Signature()
			if len(targs) > 0 {
				inst, err := types.Instantiate(nil, fn.Type(), targs, true)
				if err != nil {
					return nil, err
				}
				sig = inst.(*types.Signature)
			}
			f, ok := bnd.headerSignature(externKey(fn, targs), sig)
			if !ok {
				continue
			}

			var params []string
			for i, t := range f.Params {
				params = append(params, fmt.Sprintf("%s: %s", sig.Params().At(i).Name(), tsTypeOf(t)))
			}
			var results []string
			for _, t := range f.Results {
				results = append(results, tsTypeOf(t))
			}
			result := "void"
			switch len(results) {
			case 1:
				result = results[0]
			case 0:
			default:
				result = "[" + strings.Join(results, ", ") + "]"
			}
			fmt.Fprintf(&host, "\t%q(%s): %s;\n", f.Name, strings.Join(params, ", "), result)
		}
	}
	host.WriteString("}\n")

	// the records are plain objects with the fields by their names in JavaScript
	for _, name := range sortedNames(bnd.records) {
		fmt.Fprintf(&buf, "// %s is the record %s.\nexport interface %s {\n", tsName(name), name, tsName(name))
		for _, f := range bnd.records[name].Fields {
			fmt.Fprintf(&buf, "\t%s: %s;\n", f.JS, tsTypeOf(f.Type))
		}
		buf.WriteString("}\n\n")
	}
	buf.Write(host.Bytes())
	return buf.Bytes(), nil
}

// tsTypeOf returns the TypeScript type of a value, which crosses the boundary of a header package.
func tsTypeOf(t Type) string {
	switch t.Kind {
	case ValueRecord:
		return tsName(t.Name)
	case ValueList:
		return tsTypeOf(*t.Elem) + "[]"
	case ValueMap:
		return "Map<" + tsTypeOf(*t.Key) + ", " + tsTypeOf(*t.Elem) + ">"
	case ValueFunc:
		var params, results []string
		for i, p := range t.Func.Params {
			params = append(params, fmt.Sprintf("a%d: %s", i, tsTypeOf(p)))
		}
		for _, r := range t.Func.Results {
			results = append(results, tsTypeOf(r))
		}
		result := "void"
		switch len(results) {
		case 0:
		case 1:
			result = results[0]
		default:
			result = "[" + strings.Join(results, ", ") + "]"
		}
		return "((" + strings.Join(params, ", ") + ") => " + result + ")"
	}
	return tsType(t.Kind)
}

// tsName returns the name of the interface of a record, e.g. GeomRect for example.com/geom.Rect.
func tsName(full string) string {
	pkg, name := full, full
	if i := strings.LastIndex(full, "."); i >= 0 {
		pkg, name = full[:i], full[i+1:]
	}
	base := pkg[strings.LastIndex(pkg, "/")+1:]
	return strings.ToUpper(base[:1]) + base[1:] + name
}

func tsType(k ValueKind) string {
	switch k {
	case ValueHandle:
		return "object"
	case ValueBool:
		return "boolean"
	case ValueString:
		return "string"
	case ValueError:
		return "GoError"
	case ValueBig:
		return "bigint"
	}
	return "number"
}
