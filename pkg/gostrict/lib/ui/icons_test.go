package ui_test

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"testing"
)

var update = flag.Bool("update", false, "writes the packages of the icons")

// TestIcons generates the packages of the icons of flowbite as constants of ui.SVG from the files of nago with
// -update and checks, that they are up to date.
func TestIcons(t *testing.T) {
	embed := regexp.MustCompile(`//go:embed ([^\s]+\.svg)\s+var (\w+) core\.SVG`)
	for _, variant := range []string{"outline", "solid"} {
		src := filepath.Join("../../../../presentation/icons/flowbite", variant)
		gen, err := os.ReadFile(filepath.Join(src, "aaa.embed.gen.go"))
		if err != nil {
			t.Fatal(err)
		}
		var buf bytes.Buffer
		fmt.Fprintf(&buf, "// Code generated by TestIcons of lib/ui. DO NOT EDIT.\n\n")
		fmt.Fprintf(&buf, "// Package icons contains the %s icons of Flowbite (MIT license, Copyright (c) 2024 Themesberg, see LICENSE)\n", variant)
		fmt.Fprintf(&buf, "// like the package presentation/icons/flowbite/%s of nago, e.g. for ui.ImageIcon(icons.Home) or\n// ui.PrimaryButton(save).PreIcon(icons.FloppyDisk).\npackage icons\n\n", variant)
		buf.WriteString("import \"go.wdy.de/nago/pkg/gostrict/lib/ui\"\n\nconst (\n")
		matches := embed.FindAllStringSubmatch(string(gen), -1)
		if len(matches) < 200 {
			t.Fatalf("only %d icons in %s", len(matches), variant)
		}
		for _, m := range matches {
			svg, err := os.ReadFile(filepath.Join(src, m[1]))
			if err != nil {
				t.Fatal(err)
			}
			fmt.Fprintf(&buf, "\t%s ui.SVG = `%s`\n", m[2], bytes.TrimSpace(svg))
		}
		buf.WriteString(")\n")
		code, err := format.Source(buf.Bytes())
		if err != nil {
			t.Fatal(err)
		}

		dst := filepath.Join("icons/flowbite", variant)
		license, err := os.ReadFile(filepath.Join(src, "LICENSE"))
		if err != nil {
			t.Fatal(err)
		}
		if *update {
			if err := os.MkdirAll(dst, 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(dst, "icons.go"), code, 0o644); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(dst, "LICENSE"), license, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		old, err := os.ReadFile(filepath.Join(dst, "icons.go"))
		if err != nil || !bytes.Equal(old, code) {
			t.Errorf("%s is out of date, run go test -run TestIcons -update ./lib/ui/", dst)
		}
	}
}
