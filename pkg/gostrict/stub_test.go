//go:generate go test -run TestStubs -update .

var update = flag.Bool("update", false, "write the stubs of the standard library")

// TestStubs generates the stubs of the allowed packages of the standard library from the sources of the
// installed Go into _stubs, which the loader embeds, so that a compiler needs no Go installation. Without
// -update, it checks, that the embedded stubs are up to date.
func TestStubs(t *testing.T) {
	var paths []string
	for p := range stdAllowed {
		paths = append(paths, p)
	}
	slices.Sort(paths)

	for _, p := range paths {
		src, err := stdStub(p, stdAllowed[p])
		if err != nil {
			t.Fatalf("%s: %v", p, err)
		}

		file := filepath.Join("_stubs", filepath.FromSlash(p), path.Base(p)+".go")
		if *update {
			if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(file, src, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}

		old, err := os.ReadFile(file)
		if err != nil || !bytes.Equal(old, src) {
			t.Errorf("%s is out of date, run go generate in pkg/gostrict", file)
		}
	}
}

// stdStub returns a stub of the package of the standard library with the allowed functions and types and all
// constants.
func stdStub(importPath string, allowed map[string]bool) ([]byte, error) {
	bp, err := build.Import(importPath, "", 0)
	if err != nil {
		return nil, err
	}

	fset := token.NewFileSet()
	merged := &ast.File{Name: ast.NewIdent(bp.Name)}
	imports := map[string]*ast.ImportSpec{}
	for _, name := range bp.GoFiles {
		f, err := parser.ParseFile(fset, filepath.Join(bp.Dir, name), nil, 0)
		if err != nil {
			return nil, err
		}

		stub(f, func(d ast.Decl) bool {
			switch d := d.(type) {
			case *ast.FuncDecl:
				return d.Recv == nil && allowed[d.Name.Name]
			case *ast.GenDecl:
				switch d.Tok {
				case token.IMPORT, token.CONST:
					return true
				case token.TYPE:
					d.Specs = slices.DeleteFunc(d.Specs, func(s ast.Spec) bool { return !allowed[s.(*ast.TypeSpec).Name.Name] })
					return len(d.Specs) > 0
				}
			}
			return false
		})

		for _, d := range f.Decls {
			if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.IMPORT {
				for _, s := range g.Specs {
					imports[s.(*ast.ImportSpec).Path.Value] = s.(*ast.ImportSpec)
				}
				continue
			}
			merged.Decls = append(merged.Decls, d)
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by TestStubs from the sources of Go. DO NOT EDIT.\n\n")
	buf.WriteString("package " + bp.Name + "\n\n")
	var importPaths []string
	for p := range imports {
		importPaths = append(importPaths, p)
	}
	slices.Sort(importPaths)
	for _, p := range importPaths {
		buf.WriteString("import " + p + "\n")
	}
	for _, d := range merged.Decls {
		buf.WriteString("\n")
		if err := format.Node(&buf, fset, d); err != nil {
			return nil, err
		}
		buf.WriteString("\n")
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, err
	}
	return bytes.ReplaceAll(src, []byte("\n\n\n"), []byte("\n\n")), nil
}

// TestNoToolchain ensures, that the compiler does not need a Go installation at runtime.
func TestNoToolchain(t *testing.T) {
	files, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range files {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), name, nil, parser.ImportsOnly)
		if err != nil {
			t.Fatal(err)
		}
		for _, imp := range f.Imports {
			switch imp.Path.Value {
			case `"go/build"`, `"go/importer"`, `"os/exec"`:
				t.Errorf("%s imports %s, which needs a Go installation", name, imp.Path.Value)
			}
		}
	}
}
