// Command unpackgen writes the unpackers of the frame-of-reference value stream of package tsdb (see forcodec.go
// there): for each bit width 0..64 a function, which unpacks a group of 64 deltas, adds the base of their sub-block to
// each and sums them up from prev. A value j of a group lies in the bits [j*w, (j+1)*w) of the little-endian words of
// the group. The shifts are constants, so that a value costs a shift, a mask and two additions.
//
//	go run ./internal/unpackgen unpack_gen.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: unpackgen <file>")
		os.Exit(2)
	}
	var b bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	p(`// Copyright (c) 2026 worldiety GmbH
//
// This file is part of the NAGO Low-Code Platform.
// Licensed under the terms specified in the LICENSE file.
//
// SPDX-License-Identifier: Custom-License

// Code generated by internal/unpackgen. DO NOT EDIT.

package tsdb

import "encoding/binary"

`)
	for w := 0; w <= 64; w++ {
		p("func unpackDelta%d(in []byte, base, prev int64, out *[64]int64) int64 {\n", w)
		if w == 0 {
			p("\t_ = in\n\tfor j := range out {\n\t\tprev += base\n\t\tout[j] = prev\n\t}\n\treturn prev\n}\n\n")
			continue
		}
		p("\t_ = in[%d]\n", 8*w-1)
		if w < 64 {
			p("\tconst m = uint64(0x%X)\n", (uint64(1)<<uint(w))-1)
		}
		p("\tc := binary.LittleEndian.Uint64(in[0:])\n")
		cur := 0
		for j := 0; j < 64; j++ {
			bit := j * w
			word, sh := bit/64, bit%64
			if word != cur {
				p("\tc = binary.LittleEndian.Uint64(in[%d:])\n", 8*word)
				cur = word
			}
			var x string
			switch {
			case sh+w <= 64 && w == 64:
				x = "c"
			case sh+w <= 64 && sh == 0:
				x = "c & m"
			case sh+w == 64:
				x = fmt.Sprintf("c >> %d", sh)
			case sh+w < 64:
				x = fmt.Sprintf("(c >> %d) & m", sh)
			default:
				// the value goes on in the next word
				p("\tn%d := binary.LittleEndian.Uint64(in[%d:])\n", j, 8*(word+1))
				x = fmt.Sprintf("((c >> %d) | (n%d << %d)) & m", sh, j, 64-sh)
				p("\tprev += base + int64(%s)\n\tout[%d] = prev\n", x, j)
				p("\tc = n%d\n", j)
				cur = word + 1
				continue
			}
			p("\tprev += base + int64(%s)\n\tout[%d] = prev\n", x, j)
		}
		p("\treturn prev\n}\n\n")
	}
	p("// unpackDelta are the unpackers by bit width.\nvar unpackDelta = [65]func(in []byte, base, prev int64, out *[64]int64) int64{\n")
	for w := 0; w <= 64; w++ {
		p("\tunpackDelta%d,\n", w)
	}
	p("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[1], src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
